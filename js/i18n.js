  let current = null;

  function getLang() {
    if (current) return current;
    let stored = null;
    try { stored = localStorage.getItem(STORAGE_KEY); } catch {}
    current = SUPPORTED.includes(stored) ? stored : "en"; // 出海定位：默认英文
    return current;
  }

  function setLang(lang) {
    if (!SUPPORTED.includes(lang)) lang = "en";
    if (lang === current) { return lang; }
    current = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch {}
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    }
    if (typeof window !== "undefined" && typeof window.dispatchEvent === "function") {
      window.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
    }
    return lang;
  }

  function t(key, params) {
    const d = DICT[getLang()] || DICT.en;
    let s = d[key];
    if (s === undefined) s = (DICT.en[key] !== undefined) ? DICT.en[key] : (DICT.zh[key] !== undefined ? DICT.zh[key] : `[[${key}]]`);
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.split("{" + k + "}").join(String(v));
      }
    }
    return s;
  }

  function initI18n() {
    const lang = getLang();
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    }
    return lang;
  }

  return { t, setLang, getLang, initI18n, SUPPORTED, STORAGE_KEY };
